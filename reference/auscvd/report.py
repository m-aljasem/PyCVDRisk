def calculator_rows():
    c = pd.read_csv(HERE / "fixtures" / "calculator_reference.csv")
    out = []
    for eq, g in c.groupby("equation"):
        ours = np.maximum(100 * T._ours(g, eq == "diabetes"), g.factor)
        out.append((eq, len(g), int((np.floor(ours + 0.5) == g.shown).sum()),
                    float(np.max(np.abs(ours - g.unrounded) / g.unrounded))))
    return out


def band_drops():
    """Fixture general-equation profiles whose risk (unrounded, shown) falls when age moves across a band edge."""
    c = pd.read_csv(HERE / "fixtures" / "calculator_reference.csv")
    g = c[c.equation == "general"]
    out = []
    for sex, edges in (("female", (45, 55, 60, 65, 70)), ("male", (55, 60, 65))):
        h = g[g.sex == (sex == "male")]
        for edge in edges:
            risk = [np.maximum(100 * auscvd(age, sex, h.smoking.map(T.SMOKING), h.sbp, h.tc_hdl, h.diabetes, h.af, h.bp,
                                            h.lipid, h.antithrombotic, h.quintile), M._factor(np.array([age]), sex))
                    for age in (edge - 1, edge)]
            shown = [np.floor(r + 0.5) for r in risk]
            out.append((sex, edge, len(h), int((risk[1] < risk[0]).sum()), int((shown[1] < shown[0]).sum())))
    return out


