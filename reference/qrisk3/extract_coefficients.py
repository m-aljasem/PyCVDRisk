"""Generate src/cvd_risk/qrisk3/coefficients.py from ClinRisk's C source, keeping every
literal exactly as printed. Run from repo root: python reference/qrisk3/extract_coefficients.py
(tests/qrisk3 re-parses the C and checks the committed file still matches).
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).parents[2]
SRC = Path(__file__).parent / "source" / "qrisk3_2017.c"
OUT = ROOT / "src" / "cvd_risk" / "qrisk3" / "coefficients.py"
NUM = r"(-?\d+\.?\d*(?:[eE]-?\d+)?)"


def parse(body: str) -> dict:
    arr = lambda name: re.findall(NUM + r",?\s*\n", re.search(name + r"\[\d+\] = \{(.*?)\};", body, re.S).group(1) + "\n")  # noqa: E731
    survivor = [v for v in arr("survivor")]
    m = {
        "survivor": survivor[10],  # index surv=10: the 10-year horizon
        "ethnicity": tuple(arr("Iethrisk")),
        "smoking": tuple(arr("Ismoke")),
        "age_powers": tuple(re.findall(r"double age_\d = (?:pow\(dage,(-?[\d.]+)\)|(dage));", body)),
        "means": dict(re.findall(r"^\s*(\w+) = \1 - " + NUM + ";", body, re.M)),
        "terms": {},
    }
    m["age_powers"] = tuple((int(float(p)) if float(p).is_integer() else float(p)) if p else 1
                            for p, _ in m["age_powers"])
    for lhs, coef in re.findall(r"a \+= ([^;]*?) \* " + NUM + ";", body):
        parts = tuple(p.strip() for p in lhs.split("*"))
        parts = tuple(re.sub(r"\(smoke_cat==(\d)\)", r"smoke_\1", p) for p in parts)
        m["terms"][parts] = coef
    return m


def models() -> dict:
    text = SRC.read_text()
    female, male = re.split(r"static double cvd_male_raw", text)
    return {"female": parse(female), "male": parse(male)}


def render(ms: dict, name="QRISK3-2017", pkg="qrisk3", src="qrisk3_2017.c", year=2017) -> str:
    out = [
        f'"""{name} coefficients, generated by reference/{pkg}/extract_coefficients.py from',
        f"ClinRisk's C source (reference/{pkg}/source/{src}). Every literal is copied as printed.",
        "",
        f"Copyright {year} ClinRisk Ltd. Released by ClinRisk under the GNU Lesser General Public",
        "License v3 or later; this file is a derivative and carries the same licence. See",
        f"src/cvd_risk/{pkg}/LICENSE.",
        '"""',
        "",
        f'SOURCE = "ClinRisk Ltd., {name} open source release (https://qrisk.org), LGPL-3.0-or-later"',
        "",
        "MODELS = {",
    ]
    for sex, m in ms.items():
        out += [f'    "{sex}": {{',
                f'        "survivor": {m["survivor"]},',
                f'        "ethnicity": ({", ".join(m["ethnicity"])}),',
                f'        "smoking": ({", ".join(m["smoking"])}),',
                f'        "age_powers": {m["age_powers"]},',
                '        "means": {', *[f'            "{k}": {v},' for k, v in m["means"].items()], "        },",
                '        "terms": {', *[f"            {k!r}: {v}," for k, v in m["terms"].items()], "        },",
                "    },"]
    return "\n".join(out + ["}", ""])


if __name__ == "__main__":
    OUT.write_text(render(models()))
    print(f"wrote {OUT}")
