"""Build reference/finrisk/REPORT.md. Run from repo root: python reference/finrisk/report.py

1. Table 1 of Vartiainen 2020 (FINRISKI 2.0), transcribed by eye from source/vartiainen2020_table1.jpg,
   is rebuilt from the package's BETA.
2. The official calculator (fixtures/calculator_reference.jsonl, from run_calculator.py) is compared
   patient by patient, CHD and stroke.
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

import numpy as np

from cvd_risk import finrisk
from cvd_risk.finrisk.finrisk import BETA

HERE = Path(__file__).parent
FX = HERE / "fixtures" / "calculator_reference.jsonl"
# Table 1 as printed (decimal commas -> points), terms in the package's BETA order
TABLE1 = {
    ("male", "chd"): "9.081 - 0.075 ikä - 0.579 tupakointi - 0.320 kolesteroli - 0.011 verenpaine + 1.082 HDL "
                     "- 0.729 diabetes - 0.338 vanhempien",
    ("male", "stroke"): "9.928 - 0.083 ikä - 0.369 tupakointi - 0.014 verenpaine + 0.329 HDL - 0.705 diabetes "
                        "- 0.249 vanhempien",
    ("female", "chd"): "11.250 - 0.095 ikä - 0.639 tupakointi - 0.244 kolesteroli - 0.013 verenpaine + 0.845 HDL "
                       "- 1.315 diabetes - 0.421 vanhempien",
    ("female", "stroke"): "9.553 - 0.085 ikä - 0.613 tupakointi - 0.012 verenpaine + 0.623 HDL - 0.914 diabetes "
                          "- 0.023 vanhempien",
}
NAMES = ("ikä", "tupakointi", "kolesteroli", "verenpaine", "HDL", "diabetes", "vanhempien")
OPTIMAL = dict(smoker=0, total_chol=4.0, hdl_chol=1.5, sbp=110, diabetes=0, parent_mi=0, parent_stroke=0)


def table1(sex, outcome):
    """The printed form, rebuilt from BETA: 1 / (1 + exp(-b0 - b.x)), written as exp(c0 - c.x)."""
    b0, age, smk, tc, sbp, hdl, dm, par = BETA[(sex, outcome)]
    s = f"{-b0:.3f}"
    for name, v in zip(NAMES, (age, smk, tc, sbp, hdl, dm, par)):
        if v:
            s += f" {'-' if v > 0 else '+'} {abs(v):.3f} {name}"
    return s


def calculator():
    """Rows of the official calculator with the package's CHD and stroke risk and the optimal-profile risk."""
    rows = [json.loads(ln) for ln in FX.read_text().splitlines()]
    out = []
    for r in rows:
        args = {k: r[k] for k in ("age", "sex", "smoker", "total_chol", "hdl_chol", "sbp", "diabetes",
                                  "parent_mi", "parent_stroke")}
        opt = {**args, **OPTIMAL}
        for o, key in (("chd", "coronary"), ("stroke", "stroke")):
            out.append(dict(id=r["id"], outcome=o, official=r["response"][key]["absoluteRisk"],
                            official_optimal=r["response"][key]["optimalRisk"],
                            package=float(finrisk(**args, outcome=o)), package_optimal=float(finrisk(**opt, outcome=o))))
    return out


def summary():
    c = calculator()
    off, pk = np.array([x["official"] for x in c]), np.array([x["package"] for x in c])
    oo, po = np.array([x["official_optimal"] for x in c]), np.array([x["package_optimal"] for x in c])
    floored = off == oo  # the calculator shows the optimal-profile risk when the person's own risk is lower
    return dict(n_patients=len(c) // 2, n=len(c), floored=int(floored.sum()),
                floored_below=bool(np.all(pk[floored] <= po[floored])),
                rel=float(np.max(np.abs(pk[~floored] - off[~floored]) / off[~floored])),
                rel_optimal=float(np.max(np.abs(po - oo) / oo)))


def main():
    eq = {k: table1(*k) == v for k, v in TABLE1.items()}
    s = summary()
    L = ["# FINRISK calculator: verification report", "", f"Generated by `reference/finrisk/report.py`.", "",
         "Model: FINRISKI 2.0 (Vartiainen, Laatikainen, Jousilahti, Peltonen, Niiranen, Salomaa; Suomen Lääkärilehti",
         "2020;75:2778-84), the model of the official Finnish calculator. It replaced the package's earlier FINRISK",
         "2016 implementation (Global Heart 2016;11:213; its checks are in this file's git history).", "",
         "Evidence level A + C: the official calculator (Duodecim, forms.ebmedscloud.org/en-GB/questionnaire/finriski)",
         "and the article's Table 1.", "",
         "## 1. Equations vs Table 1", "",
         "The article's text is behind a login; Table 1 is an open image on its web page",
         "(`source/vartiainen2020_table1.jpg`), transcribed by eye. The equations rebuilt from the package's",
         "coefficients:", "",
         *[f"- {sx} {o}: {'equal to' if ok else 'DIFFERENT FROM'} Table 1" for (sx, o), ok in eq.items()], "",
         "Combined risk is 1 - (1 - CHD risk)(1 - stroke risk) (Table 1; also the calculator's page code,",
         "`source/duodecim_finriski_result_chunk.js`). The 2016 paper defined it as the sum.", "",
         "## 2. Official calculator", "",
         f"`run_calculator.py` sent {s['n_patients']} seeded patients (ages 30-64, both sexes) to the calculator's",
         f"server; it returns CHD and stroke risk ({s['n']} values) and the risk of an \"optimal\" profile of the same age",
         "and sex.", "",
         f"- {s['n'] - s['floored']} values: max relative difference {s['rel']:.1e}.",
         f"- {s['floored']} values: the calculator shows the optimal-profile risk instead of the person's own; the",
         f"  package's risk is {'at most that in every one' if s['floored_below'] else 'NOT always lower'}. So the",
         "  calculator floors its display at the optimal profile; this is not in the article, and the package does not.",
         f"- Optimal profile: non-smoker, total cholesterol 4.0, HDL 1.5 mmol/L, SBP 110, no diabetes or family",
         f"  history (solved from the calculator's values; not documented): max relative difference {s['rel_optimal']:.1e}.",
         ""]
    (HERE / "REPORT.md").write_text("\n".join(L) + "\n")
    print(f"equations {sum(eq.values())}/4; calculator {s}")
    assert all(eq.values()) and s["rel"] < 1e-12 and s["floored_below"] and s["rel_optimal"] < 1e-12


if __name__ == "__main__":
    main()
