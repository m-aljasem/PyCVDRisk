"""Build reference/edacs/REPORT.md. Run from repo root: python reference/edacs/report.py"""

from __future__ import annotations

import csv
import datetime as dt
import itertools
import json
from pathlib import Path

import numpy as np

from cvd_risk import edacs

HERE = Path(__file__).parent
FX = HERE / "fixtures"
BASE = {"age": 30, "sex": "female", "known_cad": 0, "risk_factors": 0, "diaphoresis": 0,
        "radiates_arm_shoulder": 0, "pleuritic": 0, "palpation": 0}
BANDS = [((18, 45), 2), ((46, 50), 4), ((51, 55), 6), ((56, 60), 8), ((61, 65), 10), ((66, 70), 12),
         ((71, 75), 14), ((76, 80), 16), ((81, 85), 18), ((86, 110), 20)]  # Box 3, a)
RULES = [(f"age {a}", {"age": a}, pts) for (lo, hi), pts in BANDS for a in (lo, hi)] + [
    ("male", {"sex": "male"}, 2 + 6), ("age 50, known CAD", {"age": 50, "known_cad": 1}, 4 + 4),
    ("age 50, 3 risk factors", {"age": 50, "risk_factors": 3}, 4 + 4),
    ("age 50, 2 risk factors", {"age": 50, "risk_factors": 2}, 4),
    ("age 51, known CAD", {"age": 51, "known_cad": 1}, 6), ("diaphoresis", {"diaphoresis": 1}, 2 + 3),
    ("radiates to arm or shoulder", {"radiates_arm_shoulder": 1}, 2 + 5),
    ("pain with inspiration", {"pleuritic": 1}, 2 - 4), ("pain on palpation", {"palpation": 1}, 2 - 6),
]


def box3(age, male, cad, rf, dia, rad, insp, palp):
    """Box 3 read literally as a lookup table, independent of the package's arithmetic."""
    pts = next(p for (lo, hi), p in BANDS if lo <= age <= hi)
    return pts + 6 * male + 4 * (age <= 50 and (cad or rf >= 3)) + 3 * dia + 5 * rad - 4 * insp - 6 * palp


def grid():
    """Every integer input combination: ages 18-110, sex, known CAD, 0-5 risk factors, four symptoms."""
    g = np.array(list(itertools.product(range(18, 111), (0, 1), (0, 1), range(6), *[(0, 1)] * 4)), float)
    ours = edacs(g[:, 0], np.where(g[:, 1] == 1, "male", "female"), *g[:, 2:].T)
    want = np.array([box3(*map(int, r)) for r in g])
    return len(g), int((ours == want).sum()), float(np.abs(ours - want).max())


MDCALC_WANT = {"sex": [0, 6], "artery_disease_risk_factors": [0, 4], "diaphoresis": [0, 3], "radiates": [0, 5],
               "pain_inspiration": [0, -4], "pain_palpation": [0, -6]}


def mdcalc():
    """Points and conditions on MDCalc's EDACS form (calc 1858), from the page's input schema."""
    sch = json.loads((HERE / "source" / "mdcalc_1858_schema.json").read_text())["input_schema"]
    items = {i["name"]: i for i in sch if i.get("name")}
    ok = sum([o["value"] for o in items[k]["options"]] == v for k, v in MDCALC_WANT.items())
    return ok, len(MDCALC_WANT), items["artery_disease_risk_factors"]["conditionality"]


def main():
    p = list(csv.DictReader((FX / "patients.csv").open()))
    ref = np.array([float(r["score"]) for r in csv.DictReader((FX / "reference.csv").open())])
    c = lambda k: np.array([x[k] for x in p])
    f = lambda k: c(k).astype(float)
    ours = edacs(f("age"), c("sex"), f("known_cad"), f("risk_factors"), f("diaphoresis"), f("radiates"),
                 f("pleuritic"), f("palpation"))
    same = int((ours == ref).sum())
    rules = [(n, float(edacs(**{**BASE, **kw})), w) for n, kw, w in RULES]
    ok = sum(g == w for _, g, w in rules)
    n_grid, same_grid, max_grid = grid()
    md_ok, md_n, md_cond = mdcalc()
    L = ["# EDACS: verification report", "", f"Generated by `reference/edacs/report.py`.", "",
         "## 1. Source (evidence level C)", "",
         "Than et al., Emerg Med Australas 2014, Box 3 (`source/than2014.pdf`). Every age band is checked at",
         "both ends; other items are checked on a woman aged 30 (2 points).", "",
         "| Rule | Score | Expected |", "|---|---:|---:|"]
    L += [f"| {n} | {g:g} | {w} |" for n, g, w in rules]
    L += ["", f"{ok}/{len(rules)} rules give the published points.", "",
          "### Exhaustive grid", "",
          "Box 3 read as a lookup table (`box3()` in `report.py`), against the package, over every integer",
          "input combination: ages 18-110 x sex x known CAD x 0-5 risk factors x the four symptoms.", "",
          f"{same_grid}/{n_grid} identical scores (max difference {max_grid:g}).", "",
          "## 2. RiskScorescvd (evidence level B)", "",
          *[f"- {v}" for v in (FX / "VERSION").read_text().splitlines()], "",
          "RiskScorescvd has no known-CAD input: its +4 applies to >= 3 risk factors only. The fixtures",
          "therefore set known CAD to 0; the CAD rule is covered in section 1. 40% of ages are band edges.", "",
          f"{len(p)} random patients aged 18-99 (seed 2014): {same}/{len(p)} identical scores.", "",
          "## 3. Third-party calculators (evidence level B, rules only)", "",
          "No developer calculator exists: edacs.org and www.edacs.org redirect, live and in",
          "every Wayback capture (2014-10-05, 2015-08-02), to Sussex Community NHS's unrelated Eating and Drinking",
          "Ability Classification System; the paper gives no URL; no EDACS app from the developers was found.",
          "MDCalc (calc 1858) names Than and Flaws as creators, but its scoring code is server side and was not",
          "queried. Its form (`source/mdcalc_1858_schema.json`):", "",
          f"- {md_ok}/{md_n} items carry Box 3's points; age bands in its table equal Box 3; the CAD / risk-factor",
          f"  item is shown only when `{md_cond}`.",
          "- Wording differs: MDCalc's radiation item reads \"arm, shoulder, neck, or jaw\"; Box 3 and Table 2 say",
          "  \"arm or shoulder\" (throat radiation was tested and dropped, Table 1). Ambiguity on MDCalc's side;",
          "  the package follows the paper.",
          "- cliot 1.0.0 (CRAN), `edacs_chest_pain_score()` (cut out unmodified to `source/cliot_edacs.R`), read",
          "  but not run: same bands and points, but its +4 for known CAD or >= 3 risk factors applies at every",
          "  age, not only 18-50 (cliot's error against Box 3 c). `run_cliot.R` runs it over the grid.", "",
          "Downloaded (sha256):", "",
          "- `source/mdcalc_1858_schema.json`: extracted from the `__NEXT_DATA__` of",
          "  https://www.mdcalc.com/calc/1858/emergency-department-assessment-chest-pain-score-edacs",
          "  (31fc857fc1e131087f469c07e6a1ed7a4f91fd3f9f240bb3b26a3e667307ad57)",
          "- `source/cliot_edacs.R`: lines 14605-14699 of R/neelpackage.R in",
          "  https://cran.r-project.org/src/contrib/cliot_1.0.0.tar.gz (tarball",
          "  83794e0c8a3f15434a61678558bcc19e30bc42139122f797183727ac019aa1bd; excerpt",
          "  cf737149578f17395f3dd6b2b82b6d18cae0348bdeec46534847585d9f4ae021)", "",
          "## 4. Differences by design", "",
          "- Ages are taken in completed years (50.5 counts as 50); RiskScorescvd mixes `Age < 51` and `Age <= 50`.",
          "- Ages under 18 give NaN (the score is for adults); RiskScorescvd gives 0 age points.",
          "- The EDACS-ADP (score < 16, no new ischaemia, negative 0 and 2 h troponins) is left to the caller."]
    (HERE / "REPORT.md").write_text("\n".join(L) + "\n")
    print(f"rules {ok}/{len(rules)}; grid {same_grid}/{n_grid}; MDCalc {md_ok}/{md_n}; RiskScorescvd {same}/{len(p)}")
    assert ok == len(rules) and same == len(p) and same_grid == n_grid and md_ok == md_n


if __name__ == "__main__":
    main()
